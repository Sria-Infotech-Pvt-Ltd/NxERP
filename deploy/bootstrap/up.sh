#!/usr/bin/env bash
# One command to bring up the NXERP dev platform (frappe + erpnext + helpdesk + nxerp on one site).
#
#   ./deploy/bootstrap/up.sh            build/start in the foreground (first run takes a long time)
#   ./deploy/bootstrap/up.sh -d         detached; follow with: docker compose -p nxerp-dev logs -f bench
#   ./deploy/bootstrap/up.sh down       stop (data volumes are kept)
#
# Needs: Docker with Compose v2. On Windows run it from Git Bash or WSL.
# Creates deploy/bootstrap/.env (git-ignored) with generated passwords on first run.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
env_file="$here/.env"

if [ ! -f "$env_file" ]; then
	gen() { head -c 24 /dev/urandom | base64 | tr -d '/+=' | head -c 24; }
	umask 077
	cat >"$env_file" <<EOF
# Generated by deploy/bootstrap/up.sh. Local only, never commit.
NXERP_DB_ROOT_PASSWORD=$(gen)
NXERP_ADMIN_PASSWORD=$(gen)
EOF
	echo "Created $env_file (the Administrator password for the dev site is in it)."
fi

# Use the sibling Helpdesk checkout (../helpdesk) when it exists; otherwise bootstrap uses the pinned fork commit
if [ -d "$here/../../../helpdesk/.git" ]; then
	HELPDESK_HOST_PATH="$(cd "$here/../../../helpdesk" && pwd)"
	export HELPDESK_HOST_PATH
	export HELPDESK_REF="${HELPDESK_REF:-$(git -C "$HELPDESK_HOST_PATH" branch --show-current)}"
else
	mkdir -p "$here/.no-helpdesk"
	unset HELPDESK_REF
fi

cmd=(docker compose --env-file "$here/../versions.env" --env-file "$env_file" -f "$here/../docker/compose/dev/compose.yaml")

case "${1:-}" in
	down) exec "${cmd[@]}" down ;;
	*) exec "${cmd[@]}" up "$@" ;;
esac
