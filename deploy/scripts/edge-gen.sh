#!/usr/bin/env bash
# Generates the edge configuration for ANY number of stacks from deploy/env/isolated/stacks.list (Phase 5C). No hand edits.
#
#   deploy/scripts/edge-gen.sh
#
# Reads:   deploy/env/isolated/stacks.list        one line per stack: <name> <host-prefix> <standard|restricted>
#          deploy/env/isolated/<name>.env         NXERP_SITE of each stack
#          deploy/env/isolated/edge.env           NXERP_DOMAIN (required), NXERP_LEGACY_HOST and NXERP_LEGACY_STACK (optional)
# Writes:  deploy/docker/compose/isolated/edge/generated/default.conf.template   shared part + one server block per stack
#          deploy/docker/compose/isolated/edge/generated/edge.networks.override.yaml   joins the edge to every stack's network
# Both are git-ignored and rebuilt on every run. No secret is read or written (only site names and host names).
set -euo pipefail

ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"
ENV_DIR=deploy/env/isolated
EDGE_DIR=deploy/docker/compose/isolated/edge
OUT_DIR="$EDGE_DIR/generated"

fatal() { printf '[edge-gen.sh] ERROR: %s\n' "$*" >&2; exit 1; }
env_value() { [ -f "$1" ] && sed -n "s/^$2=//p" "$1" | head -n 1 | tr -d '\r' || true; }

[ -f "$ENV_DIR/stacks.list" ] || fatal "no $ENV_DIR/stacks.list (copy $ENV_DIR/stacks.list.example)"
[ -f "$ENV_DIR/edge.env" ] || fatal "no $ENV_DIR/edge.env (copy $ENV_DIR/edge.env.example)"
domain="$(env_value "$ENV_DIR/edge.env" NXERP_DOMAIN)"
[[ "$domain" =~ ^[A-Za-z0-9.-]+$ ]] || fatal "NXERP_DOMAIN in $ENV_DIR/edge.env is empty or not a host name"

# render STACK HOST SITE: one server block from the template (only these three tokens are replaced)
render() {
	local text
	text="$(cat "$EDGE_DIR/server.block.template")"
	text="${text//\$\{STACK\}/$1}"
	text="${text//\$\{HOST\}/$2}"
	text="${text//\$\{NXERP_SITE\}/$3}"
	printf '%s\n' "$text"
}

mkdir -p "$OUT_DIR"
conf="$OUT_DIR/default.conf.template"
override="$OUT_DIR/edge.networks.override.yaml"
{
	printf '# GENERATED by deploy/scripts/edge-gen.sh from deploy/env/isolated/stacks.list. Do not edit: run the script again.\n\n'
	cat "$EDGE_DIR/nginx.conf.template"
} >"$conf"
stack_names=()
stack_hosts=()

count=0
while read -r name prefix tier _rest; do
	case "$name" in '' | '#'*) continue ;; esac
	[ -n "${prefix:-}" ] && [ -n "${tier:-}" ] || fatal "stacks.list line for '$name' needs three fields: <name> <host-prefix> <standard|restricted>"
	[[ "$name" =~ ^[a-z0-9][a-z0-9-]*$ ]] || fatal "stack name '$name' must be lowercase letters, digits and dashes"
	[[ "$prefix" =~ ^[a-z0-9][a-z0-9-]*$ ]] || fatal "host prefix '$prefix' must be lowercase letters, digits and dashes"
	case "$tier" in standard | restricted) ;; *) fatal "tier of '$name' must be standard or restricted, not '$tier'" ;; esac
	site="$(env_value "$ENV_DIR/$name.env" NXERP_SITE)"
	[ -n "$site" ] || fatal "$ENV_DIR/$name.env is missing or has no NXERP_SITE"
	[[ "$site" =~ ^[A-Za-z0-9.-]+$ ]] || fatal "NXERP_SITE of '$name' is not a host name"
	{
		printf '\n# stack %s (tier %s)\n' "$name" "$tier"
		render "$name" "$prefix.$domain" "$site"
	} >>"$conf"
	stack_names+=("$name")
	stack_hosts+=("$prefix.$domain")
	count=$((count + 1))
done < <(tr -d '\015' <"$ENV_DIR/stacks.list")
[ "$count" -ge 1 ] || fatal "$ENV_DIR/stacks.list lists no stack"

legacy_host="$(env_value "$ENV_DIR/edge.env" NXERP_LEGACY_HOST)"
if [ -n "$legacy_host" ]; then
	legacy_stack="$(env_value "$ENV_DIR/edge.env" NXERP_LEGACY_STACK)"
	[[ "$legacy_host" =~ ^[A-Za-z0-9.-]+$ ]] || fatal "NXERP_LEGACY_HOST is not a host name"
	awk -v n="$legacy_stack" '$1 == n {found = 1} END {exit !found}' "$ENV_DIR/stacks.list" || fatal "NXERP_LEGACY_STACK '$legacy_stack' is not in stacks.list"
	{
		printf '\n# legacy host, routed to stack %s\n' "$legacy_stack"
		render "$legacy_stack" "$legacy_host" "$(env_value "$ENV_DIR/$legacy_stack.env" NXERP_SITE)"
	} >>"$conf"
fi

# The edge joins every stack's network and answers there to EVERY stack host name, so a stack's backend can call another stack's public
# name (server to server, for example the OAuth token call to the identity site) without leaving the host or needing a hairpin route.
{
	printf '# GENERATED by deploy/scripts/edge-gen.sh. Do not edit.\nservices:\n  edge:\n    networks:\n'
	for name in "${stack_names[@]}"; do
		printf '      nxerp-%s_default:\n        aliases:\n' "$name"
		for host in "${stack_hosts[@]}"; do printf '          - %s\n' "$host"; done
	done
	printf 'networks:\n'
	for name in "${stack_names[@]}"; do printf '  nxerp-%s_default:\n    external: true\n' "$name"; done
} >"$override"
printf '[edge-gen.sh] wrote %s and %s (%s stack(s))\n' "$conf" "$override" "$count" >&2
